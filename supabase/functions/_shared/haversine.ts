export function distanceMeters(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number,
): number {
  const R = 6371000;
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

export function evaluateGpsFlags(
  accuracy: number | null | undefined,
): string | null {
  if (accuracy == null) return 'low_accuracy';
  if (accuracy < 3) return 'suspiciously_perfect_accuracy';
  if (accuracy > 100) return 'low_accuracy';
  return null;
}
